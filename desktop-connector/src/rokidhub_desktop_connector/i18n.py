from __future__ import annotations

import ctypes
import locale
import os


LANGUAGE_PREFERENCES = {"auto", "ru", "en"}


def detect_system_language(locale_name: str | None = None) -> str:
    """Return the supported UI language that best matches Windows."""
    candidate = locale_name
    if candidate is None and os.name == "nt":
        buffer = ctypes.create_unicode_buffer(85)
        if ctypes.windll.kernel32.GetUserDefaultLocaleName(buffer, len(buffer)):
            candidate = buffer.value
    if candidate is None:
        candidate = locale.getlocale()[0] or ""
    return "ru" if str(candidate).casefold().startswith("ru") else "en"


def resolve_language(preference: str, locale_name: str | None = None) -> str:
    if preference not in LANGUAGE_PREFERENCES:
        preference = "auto"
    return detect_system_language(locale_name) if preference == "auto" else preference


